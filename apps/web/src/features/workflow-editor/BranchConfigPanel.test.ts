import { flushPromises, mount } from '@vue/test-utils'
import { describe, expect, it } from 'vitest'
import { uuidSchema, type AgentVariable, type BranchNode } from '@odyssey/schemas'
import BranchConfigPanel from './BranchConfigPanel.vue'
import type { BranchEditIntent } from '@/domain/workflow/branchDrafts'
import type { BranchPanelSession } from './branchPanelSession'

const id = (n: number) => uuidSchema.parse(`0195f076-b6e6-7ef0-98db-${String(n).padStart(12, '0')}`)
const variable: AgentVariable = { id: id(10), key: 'count', displayName: 'Count', dataType: 'number', ownership: 'shared', readOnly: false, description: null, defaultValue: 0 }
const branch = (): BranchNode => ({ id: id(2), type: 'branch', name: 'Evidence', config: { cases: [{ id: id(3), label: 'Enough', match: 'all', conditions: [{ id: id(4), left: { kind: 'variable', variableId: variable.id }, operator: 'gte', right: { kind: 'literal', value: 3 } }] }], defaultCase: { id: id(5), label: 'Default' } } })
const props = () => ({ node: branch(), edges: [{ id: id(7), sourceNodeId: id(2), sourceHandleId: id(3), targetNodeId: id(8) }], variables: [variable] })
describe('Branch configuration', () => {
  it('handles Escape from form inputs without discarding an unapplied draft', async () => {
    const wrapper = mount(BranchConfigPanel, { attachTo: globalThis.document.body, props: props() })
    try {
      const name = wrapper.get<HTMLInputElement>('[aria-label="Branch name"]')
      await name.setValue('Unapplied keyboard draft')
      name.element.focus()
      await name.trigger('keydown', { key: 'Escape' })
      await flushPromises()
      const dialog = globalThis.document.querySelector('[role="dialog"]')
      expect(dialog?.textContent).toContain('Discard unapplied Branch changes?')
      expect(wrapper.emitted('close')).toBeUndefined()
      expect(name.element.value).toBe('Unapplied keyboard draft')
      const cancel = [...(dialog?.querySelectorAll('button') ?? [])].find(button => button.textContent?.trim() === 'Cancel')
      if (!cancel) throw new Error('Expected cancel button')
      cancel.click()
      await flushPromises()
      expect(name.element.value).toBe('Unapplied keyboard draft')
      expect(globalThis.document.activeElement).toBe(name.element)
    } finally { wrapper.unmount() }
  })
  it('blocks duplicate case names and lets the user correct them', async () => {
    const p = props()
    const first = p.node.config.cases[0]
    if (!first) throw new Error('Case required')
    p.node.config.cases.push({ ...structuredClone(first), id: id(30), label: 'Other', conditions: first.conditions.map(c => ({ ...c, id: id(31) })) })
    const wrapper = mount(BranchConfigPanel, { props: p })
    await wrapper.get('[aria-label="Case 2 name"]').setValue(' Enough ')
    await wrapper.get('form').trigger('submit')
    expect(wrapper.text()).toContain('Use a unique case name within this Branch.')
    expect(wrapper.emitted('apply')).toBeUndefined()
    await wrapper.get('[aria-label="Case 2 name"]').setValue('Other')
    await wrapper.get('form').trigger('submit')
    expect(wrapper.emitted('apply')).toHaveLength(1)
    expect(p.node.config.cases[1]?.label).toBe('Other')
    wrapper.unmount()
  })
  it('collapses cases independently without changing drafts, and preserves values after expanding', async () => {
    const p = props(), wrapper = mount(BranchConfigPanel, { props: p })
    await wrapper.get('[aria-label="Case 1 condition 1 right"]').setValue('8')
    await wrapper.get('[aria-label="Collapse Enough"]').trigger('click')
    expect(wrapper.get('[aria-label="Expand Enough"]').attributes('aria-expanded')).toBe('false')
    expect(wrapper.get('[aria-label="Case 1 condition 1 right"]').isVisible()).toBe(false)
    expect(wrapper.text()).toContain('1 condition · AND · Connected')
    await wrapper.get('.branch-add-case').trigger('click')
    expect(wrapper.get('[aria-label="Collapse Case 2"]').attributes('aria-expanded')).toBe('true')
    expect(wrapper.get('[aria-label="Case 2 condition 1 right"]').isVisible()).toBe(true)
    await wrapper.get('[aria-label="Expand Enough"]').trigger('click')
    expect(wrapper.get('[aria-label="Case 1 condition 1 right"]').element).toHaveProperty('value', '8')
    expect(wrapper.emitted('apply')).toBeUndefined()
    expect(p.node.config.cases[0]?.conditions[0]).toMatchObject({ right: { kind: 'literal', value: 3 } })
    wrapper.unmount()
  })
  it('opens a collapsed invalid case on Apply and never includes collapse state in the payload', async () => {
    const wrapper = mount(BranchConfigPanel, { props: props() })
    await wrapper.get('[aria-label="Case 1 condition 1 right"]').setValue('invalid number')
    await wrapper.get('[aria-label="Collapse Enough"]').trigger('click')
    await wrapper.get('form').trigger('submit')
    expect(wrapper.get('[aria-label="Collapse Enough"]').attributes('aria-expanded')).toBe('true')
    expect(wrapper.get('[aria-label="Case 1 condition 1 right"]').isVisible()).toBe(true)
    expect(wrapper.emitted('apply')).toBeUndefined()
    await wrapper.get('[aria-label="Case 1 condition 1 right"]').setValue('9')
    await wrapper.get('[aria-label="Collapse Enough"]').trigger('click')
    await wrapper.get('form').trigger('submit')
    const intent = wrapper.emitted<[BranchEditIntent]>('apply')?.[0]?.[0]
    expect(intent?.node.config.cases[0]?.conditions[0]).toMatchObject({ right: { kind: 'literal', value: 9 } })
    expect(JSON.stringify(intent)).not.toContain('collapsed')
    wrapper.unmount()
  })
  it('confirms connected-case removal, reports its target and preserves the original graph until Apply', async () => {
    const p = props(), wrapper = mount(BranchConfigPanel, { attachTo: globalThis.document.body, props: { ...p, targetNames: { [id(8)]: 'Publish brief' } } })
    try {
      await wrapper.get('[aria-label="Delete Enough"]').trigger('click'); await flushPromises()
      const dialog = globalThis.document.querySelector('[role="dialog"]')
      expect(dialog?.textContent).toContain('Publish brief')
      expect(dialog?.textContent).toContain('1 outgoing connections')
      expect(wrapper.find('[aria-label="Case 1 name"]').exists()).toBe(true)
      const confirm = [...(dialog?.querySelectorAll('button') ?? [])].find(b => b.textContent?.trim() === 'Confirm')
      if (!confirm) throw new Error('Expected confirmation button')
      confirm.click(); await flushPromises()
      expect(p.node.config.cases).toHaveLength(1)
      expect(p.edges).toHaveLength(1)
      expect(wrapper.emitted('apply')).toBeUndefined()
      await wrapper.get('form').trigger('submit')
      const emitted = wrapper.emitted<[BranchEditIntent]>('apply')?.[0]?.[0]
      expect(emitted?.node.config.cases).toEqual([])
      expect(emitted?.confirmedRemovedCaseIds).toEqual([id(3)])
    } finally { wrapper.unmount() }
  })
  it('emits valid settings only on Apply and keeps typed values and identities', async () => {
    const p = props(), wrapper = mount(BranchConfigPanel, { props: p })
    await wrapper.get('[aria-label="Branch name"]').setValue('Reviewed evidence')
    await wrapper.get('[aria-label="Case 1 condition 1 right"]').setValue('5')
    expect(wrapper.emitted('apply')).toBeUndefined()
    expect(p.node.name).toBe('Evidence')
    await wrapper.get('form').trigger('submit')
    const emitted = wrapper.emitted<[BranchEditIntent]>('apply')?.[0]?.[0]
    expect(emitted?.node).toMatchObject({ name: 'Reviewed evidence', config: { cases: [{ id: id(3), conditions: [{ right: { kind: 'literal', value: 5 } }] }] } })
    expect(emitted?.baseline).toEqual(p.node)
    expect(emitted?.baselineEdges).toEqual(p.edges)
    await wrapper.setProps({ node: emitted?.node ?? p.node })
    expect(wrapper.text()).toContain('Settings applied')
    wrapper.unmount()
  })
  it('shows a draft Case 1 for creation and refuses incomplete numeric values', async () => {
    const p = props(); p.node.config.cases = []
    const wrapper = mount(BranchConfigPanel, { props: { ...p, creating: true } })
    expect(wrapper.get('[aria-label="Case 1 name"]').element).toHaveProperty('value', 'Case 1')
    await wrapper.get('form').trigger('submit')
    expect(wrapper.emitted('apply')).toBeUndefined()
    expect(wrapper.text()).toContain('Choose an available variable')
    expect(p.node.config.cases).toEqual([])
    wrapper.unmount()
  })
  it('preserves unapplied drafts across panel switches and blocks stale edits', async () => {
    const cache = new Map<ReturnType<typeof id>, BranchPanelSession>()
    const p = props(), first = mount(BranchConfigPanel, { props: { ...p, draftCache: cache } })
    await first.get('[aria-label="Branch name"]').setValue('Local draft')
    first.unmount()
    const next = mount(BranchConfigPanel, { props: { ...p, draftCache: cache } })
    expect(next.get('[aria-label="Branch name"]').element).toHaveProperty('value', 'Local draft')
    await next.setProps({ node: { ...p.node, name: 'External edit' } })
    await next.get('form').trigger('submit')
    expect(next.emitted('apply')).toBeUndefined()
    expect(next.text()).toContain('Your draft is preserved')
    next.unmount()
  })
  it('keeps a selected variable visible when searching, and disables read-only mutation', async () => {
    const wrapper = mount(BranchConfigPanel, { props: props() })
    await wrapper.get('[aria-label="Search Branch variables"]').setValue('unrelated search')
    expect(wrapper.get('[aria-label^="Case 1 condition 1 left:"]').text()).toContain('Count')
    expect(wrapper.text()).not.toContain('This variable is unavailable')
    await wrapper.setProps({ readOnly: true })
    expect(wrapper.get('fieldset').attributes()).toHaveProperty('disabled')
    await wrapper.get('form').trigger('submit')
    expect(wrapper.emitted('apply')).toBeUndefined()
    wrapper.unmount()
  })
  it('uses styled menus for source, variable and value type without applying the draft', async () => {
    const wrapper = mount(BranchConfigPanel, { props: props() })
    expect(wrapper.find('select').exists()).toBe(false)
    await wrapper.get('[aria-label^="Case 1 condition 1 left:"]').trigger('click')
    expect(wrapper.get('[role="listbox"]').attributes('aria-label')).toBe('Case 1 condition 1 left')
    expect(wrapper.findAll('[role="option"]').find(option => option.text().includes('Count'))?.attributes('aria-selected')).toBe('true')
    await wrapper.get('[role="listbox"]').trigger('keydown', { key: 'Escape' })
    expect(wrapper.find('[role="listbox"]').exists()).toBe(false)
    await wrapper.get('[aria-label^="Case 1 condition 1 left source:"]').trigger('click')
    await wrapper.findAll('[role="option"]').find(option => option.text() === 'Value')?.trigger('click')
    await wrapper.get('[aria-label^="Case 1 condition 1 left type:"]').trigger('click')
    await wrapper.findAll('[role="option"]').find(option => option.text() === 'Boolean')?.trigger('click')
    expect(wrapper.get('[aria-label^="Case 1 condition 1 left type:"]').text()).toBe('Boolean')
    expect(wrapper.emitted('apply')).toBeUndefined()
    wrapper.unmount()
  })
  it('omits the right control for unary operators and exposes a protected fallback', async () => {
    const wrapper = mount(BranchConfigPanel, { props: props() })
    await wrapper.get('[aria-label^="Case 1 condition 1 operator:"]').trigger('click')
    const option = wrapper.findAll('[role="option"]').find(item => item.text() === 'Is empty')
    if (!option) throw new Error('Expected unary operator option')
    await option.trigger('click')
    expect(wrapper.find('[aria-label="Case 1 condition 1 right"]').exists()).toBe(false)
    expect(wrapper.find('[aria-label="Delete Default"]').exists()).toBe(false)
    expect(wrapper.text()).toContain('Default · Required')
    wrapper.unmount()
  })
})
